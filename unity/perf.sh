#!/usr/bin/env bash
set -euo pipefail

export LC_ALL=C
export LANG=C
export DOTNET_CLI_TELEMETRY_OPTOUT=1

root=$(cd -- "$(dirname -- "$0")/.." && pwd)
entities=${GI_PERF_ENTITIES:-200000}
core=${GI_PERF_CORE:-2}
backend=${1:-editor-coreclr}
logs=$root/unity/project/Logs
baseline=$root/unity/perf-baseline.json
report=$root/unity/perf.md

case $backend in
    editor-coreclr | none) ;;
    *) printf 'usage: perf.sh [editor-coreclr|none]; player backends write GI_PERF_OUT and are merged with: GI_PERF_JSON=<file> perf.sh none\n' >&2; exit 2 ;;
esac

pin=()
command -v taskset >/dev/null 2>&1 && pin=(taskset -c "$core")

mkdir -p "$logs"
references=$logs/perf-references.json

dotnet build "$root/benchmarks" -c Release -m:1 >/dev/null
dotnet build "$root/unity/tests/Gi.Frames.Runner" -c Release -m:1 >/dev/null
net=$root/benchmarks/bin/Release/net10.0/GiBenchmarks.dll
scalar=$root/unity/tests/Gi.Frames.Runner/bin/Release/net10.0/Gi.Frames.Runner.dll

frame() {
    local dll=$1 name=$2
    shift 2
    env "$@" "${pin[@]}" dotnet "$dll" --frames "${name%%:*}" ${name#*:} --entities "$entities" --measure 60 --warmup 10 2>/dev/null | tail -1
}

: >"$references.lines"
for variant in "dotnet-net10|$net|X=1" "dotnet-scalar|$scalar|X=1" "dotnet-scalar-pgo-off|$scalar|DOTNET_TieredPGO=0"; do
    label=${variant%%|*}
    rest=${variant#*|}
    dll=${rest%%|*}
    setting=${rest#*|}
    for spec in "B1:--precision exact" "C:--precision cell --layer transient --reads fused" "W:--precision cell"; do
        for repeat in 1 2 3; do
            line=$(frame "$dll" "$spec" "$setting")
            printf '%s\t%s\n' "$label" "$line" >>"$references.lines"
        done
    done
done

if [ "$backend" = editor-coreclr ]; then
    rm -f "$logs/gi-perf-editor-coreclr.json"
    GI_PERF_ENTITIES=$entities GI_PERF_SOURCES=$entities "$root/unity/validate.sh" perf
    unityjson=$logs/gi-perf-editor-coreclr.json
else
    unityjson=${GI_PERF_JSON:?set GI_PERF_JSON to a gi-perf-*.json file}
fi

python3 -I - "$baseline" "$report" "$references.lines" "$unityjson" "$entities" <<'PY'
import json
import sys

baseline_path, report_path, lines_path, unity_path, entities = sys.argv[1:6]

unity = json.load(open(unity_path))
host = unity["host"]
try:
    baseline = json.load(open(baseline_path))
except FileNotFoundError:
    baseline = {"hosts": {}}
table = baseline["hosts"].setdefault(host, {})

runs = {}
for raw in open(lines_path):
    label, _, payload = raw.rstrip("\n").partition("\t")
    frame = json.loads(payload)
    runs.setdefault((label, "frame.%s.%s" % (frame["frame"], frame["precision"])), []).append(frame)

for (label, key), frames_ in runs.items():
    values = table.setdefault(label, {})
    ordered = sorted(frames_, key=lambda f: float(f["p50_ms"]))
    middle = ordered[len(ordered) // 2]
    values[key + ".p50_ms"] = float(middle["p50_ms"])
    values[key + ".p99_ms"] = float(middle["p99_ms"])
    values[key + ".entities"] = float(middle["entities"])
    values[key + ".runs"] = float(len(ordered))
    values[key + ".p50_spread_ms"] = float(ordered[-1]["p50_ms"]) - float(ordered[0]["p50_ms"])

table[unity["backend"]] = {key: float(value) for key, value in unity["values"].items()}


def number(value):
    return "%.6f" % value


def dump(node, indent):
    pad = "  " * indent
    if isinstance(node, dict):
        if not node:
            return "{}"
        parts = []
        for key in sorted(node):
            parts.append("%s  %s: %s" % (pad, json.dumps(key), dump(node[key], indent + 1)))
        return "{\n" + ",\n".join(parts) + "\n" + pad + "}"
    return number(node)


open(baseline_path, "w", newline="\n").write(dump(baseline, 0) + "\n")


def get(label, key):
    return table.get(label, {}).get(key)


def cell(label, key):
    value = get(label, key)
    return "n/a" if value is None else "%.2f" % value


def ratio(a, b):
    if a is None or b is None or b == 0:
        return "n/a"
    return "%.2fx" % (a / b)


frames = [("B1", "exact"), ("C", "cell"), ("W", "cell")]
labels = [
    ("dotnet-net10", "dotnet, net10 build (vector), default tiering"),
    ("dotnet-scalar", "dotnet, netstandard2.1 build (scalar), default tiering"),
    ("dotnet-scalar-pgo-off", "dotnet, netstandard2.1 build (scalar), TieredPGO off"),
    ("editor-coreclr", "Unity editor, CoreCLR, netstandard2.1 build (scalar)"),
    ("coreclr-player", "Unity Linux player, CoreCLR, netstandard2.1 build (scalar)"),
    ("il2cpp-player", "Unity Linux player, IL2CPP, netstandard2.1 build (scalar)"),
]

out = []
out.append("# Gi performance in Unity")
out.append("")
out.append("Generated by `unity/perf.sh`; the numbers live in `unity/perf-baseline.json`. Do not edit by hand.")
out.append("")
out.append("## Method")
out.append("")
out.append("- **Frames.** The `benchmarks/` frame harness (B1, C, W; the same scenarios, parameters, receipts and checksums) is compiled unchanged as `GiBenchmarks.dll` for netstandard2.1 (`unity/tests/Gi.Frames`; only `AggressiveOptimization`, two intrinsics probes and `Stopwatch.GetElapsedTime` are rewritten at build time). It runs inside the Unity test and on `dotnet`, on one core, one thread, %s entities, 10 warm-up and 60 measured frames, p50 of the frame time; each dotnet row is the median of three process runs because the tiered JIT is bimodal on some frames (frame C ran at 22 ms in one process and 9 ms in the next). A run fails if the harness's receipts fail or the frame allocates." % format(int(float(entities)), ","))
out.append("- **dotnet rows** run the same harness pinned to one core. The net10 build is the vector build `src/Gi` ships for `net10.0`; Unity cannot reference it yet (`unity/ROADMAP.md`, Appendix B). The netstandard2.1 build is the scalar one Unity loads today.")
out.append("- **ECS rows** use `GiEcsFixture`: emitters (static) plus probes with a value and gradient binding on the derived layer; wall time is `Tick` plus completing every job; Gi time is the sum of the five `Gi.*` profiler markers, summed across threads. They are not frame C.")
out.append("- Backends: the editor runs CoreCLR (there is no Mono in Unity 7). Player columns are filled by the final verification pass (`unity/validate.sh`; the suite writes `GI_PERF_OUT`).")
out.append("")
for host_name in sorted(baseline["hosts"]):
    t = baseline["hosts"][host_name]
    out.append("## %s" % host_name)
    out.append("")
    out.append("### Frame time, p50 ms (lower is better)")
    out.append("")
    out.append("| Backend | B1 exact | C cell | W cell |")
    out.append("|---|---|---|---|")
    for label, title in labels:
        if label not in t:
            continue
        out.append("| %s | %s | %s | %s |" % (title, *(("%.2f" % t[label]["frame.%s.%s.p50_ms" % f]) if "frame.%s.%s.p50_ms" % f in t[label] else "n/a" for f in frames)))
    out.append("")
    ed = t.get("editor-coreclr", {})
    net = t.get("dotnet-net10", {})
    sc = t.get("dotnet-scalar", {})
    pg = t.get("dotnet-scalar-pgo-off", {})
    out.append("### Ratios for the editor (CoreCLR)")
    out.append("")
    out.append("| Frame | against dotnet net10 | against dotnet scalar, default tiering | against dotnet scalar, PGO off |")
    out.append("|---|---|---|---|")
    for f in frames:
        k = "frame.%s.%s.p50_ms" % f
        out.append("| %s %s | %s | %s | %s |" % (f[0], f[1], ratio(ed.get(k), net.get(k)), ratio(ed.get(k), sc.get(k)), ratio(ed.get(k), pg.get(k))))
    out.append("")
    out.append("### ECS and tooling costs, editor (CoreCLR)")
    out.append("")
    out.append("| Quantity | Measured |")
    out.append("|---|---|")
    rows = [
        ("Idle tick, a profile and no entities", "idle.us_per_tick", "%.1f us"),
        ("Quiet tick with %s placed sources" % format(int(ed.get("reconcile.sources", 0)), ","), "reconcile.quiet_ms", "%.2f ms"),
        ("Tick at 1%% churn (%s places and %s removes)" % (format(int(ed.get("reconcile.churn_each_way", 0)), ","), format(int(ed.get("reconcile.churn_each_way", 0)), ",")), "reconcile.frame_ms", "%.2f ms"),
        ("Per command (place or remove), churn tick minus quiet tick", "reconcile.us_per_command", "%.3f us"),
        ("Extrapolated: 10k places and 10k removes", "reconcile.ms_for_10k_each_way", "%.1f ms"),
        ("Profile edit: free, rebuild and re-place %s sources" % format(int(ed.get("profile_edit.sources", 0)), ","), "profile_edit.ms", "%.0f ms"),
        ("Mirror upload of 512 changed tiles", "mirror.upload_512_tiles_ms", "%.3f ms"),
        ("ECS frame, serial (job workers 0): wall", "ecs.serial.wall_ms", "%.2f ms"),
        ("ECS frame, serial: Gi time (markers)", "ecs.serial.gi_ms", "%.2f ms"),
        ("ECS frame, serial: ECS time as a share of Gi time", "ecs.serial.ecs_share_of_gi", "%.0f%%"),
        ("ECS frame with default job workers: wall", "ecs.workers.wall_ms", "%.2f ms"),
    ]
    for title, key, fmt in rows:
        value = ed.get(key)
        if value is None:
            text = "n/a"
        elif key == "ecs.serial.ecs_share_of_gi":
            text = fmt % (value * 100)
        else:
            text = fmt % value
        out.append("| %s | %s |" % (title, text))
    out.append("")

out.append("## Ledger")
out.append("")
out.append("Rows L1 to L11 of `unity/ROADMAP.md`, filled from this host only. A miss is a miss.")
out.append("")
host_name = sorted(baseline["hosts"])[0]
t = baseline["hosts"][host_name]
ed = t.get("editor-coreclr", {})
net = t.get("dotnet-net10", {})
sc = t.get("dotnet-scalar", {})
pg = t.get("dotnet-scalar-pgo-off", {})
c = "frame.C.cell.p50_ms"
out.append("| # | Prediction | Measured |")
out.append("|---|---|---|")
out.append("| L1 | CoreCLR, frame C Gi time against dotnet on the same host: at most 1.15x | the editor against the same scalar build on dotnet: %s with default tiering, %s with PGO off; against the vector net10 build: %s (the vector build cannot be loaded yet) |" % (ratio(ed.get(c), sc.get(c)), ratio(ed.get(c), pg.get(c)), ratio(ed.get(c), net.get(c))))
out.append("| L2 | CoreCLR, frame C wall time with sense on 8 workers: 3.6 to 4.6 ms | not measured on frame C; the ECS probe scene is in the table above (wall %s ms with workers, %s ms serial) |" % (("%.2f" % ed["ecs.workers.wall_ms"]) if "ecs.workers.wall_ms" in ed else "n/a", ("%.2f" % ed["ecs.serial.wall_ms"]) if "ecs.serial.wall_ms" in ed else "n/a"))
share = ed.get("ecs.serial.ecs_share_of_gi")
out.append("| L3 | ECS share of frame C at most 12%% of Gi time | MISSED on the probe scene: ECS time is %s of Gi time with job workers off (200,000 emitters, 200,000 probes with value and gradient). Not frame C. |" % ("%.0f%%" % (share * 100) if share is not None else "n/a"))
out.append("| L4 | Mono, 4 to 10x slower than dotnet net | not applicable: Unity 7 has no Mono |")
out.append("| L5 | IL2CPP, 1.5 to 4x slower than dotnet net | pending the final player pass |")
out.append("| L6 | 0 B managed allocation per steady tick | 0 B in the editor on every system (V-2); players pending |")
cm = ed.get("reconcile.ms_for_10k_each_way")
out.append("| L7 | Reconcile at 1%% churn of 1M sources, 10k places and 10k removes, at most 1.5 ms | %s ms extrapolated from %s sources at 1%% churn; the whole reconcile tick minus a quiet tick, so it includes the diff, the structural cleanup and `ApplyBatch` |" % (("%.1f" % cm) if cm is not None else "n/a", format(int(ed.get("reconcile.sources", 0)), ",")))
out.append("| L8 | Mirror upload of 512 changed tiles at most 0.5 ms | %s ms |" % (("%.3f" % ed["mirror.upload_512_tiles_ms"]) if "mirror.upload_512_tiles_ms" in ed else "n/a"))
out.append("| L9 | Tier D suite at most 60 s | see `unity/ROADMAP.md` |")
pe = ed.get("profile_edit.ms")
out.append("| L10 | Profile edit with 1M sources at most 250 ms | %s ms with %s sources |" % (("%.0f" % pe) if pe is not None else "n/a", format(int(ed.get("profile_edit.sources", 0)), ",")))
idle = ed.get("idle.us_per_tick")
out.append("| L11 | Idle cost at most 20 us per tick | %s us |" % (("%.1f" % idle) if idle is not None else "n/a"))
out.append("")
open(report_path, "w", newline="\n").write("\n".join(out))
PY

printf 'baseline: %s\nreport:   %s\n' "$baseline" "$report"
